export function normalizeHudLocale(input) {
  if (typeof input !== 'string') return HUD_FALLBACK_LOCALE;
  const cleaned = input.trim().replace(/_/g, '-');
  if (!cleaned) return HUD_FALLBACK_LOCALE;
  if (HUD_I18N[cleaned]) return cleaned;
  const lower = cleaned.toLowerCase();
  if (lower === 'zh' || lower.startsWith('zh-')) {
    return 'zh-Hans';
  }
  if (lower === 'en' || lower.startsWith('en-')) return 'en';
  const base = lower.split('-')[0];
  if (base && HUD_I18N[base]) return base;
  return HUD_I18N.en ? 'en' : HUD_FALLBACK_LOCALE;
}

export function hudText(locale, key, params) {
  const resolved = normalizeHudLocale(locale);
  const pack = HUD_I18N[resolved] || HUD_I18N.en || HUD_I18N[HUD_FALLBACK_LOCALE];
  const fallbackPack = HUD_I18N.en || HUD_I18N[HUD_FALLBACK_LOCALE];
  let template = pack[key];
  if (typeof template !== 'string') template = fallbackPack[key];
  if (typeof template !== 'string') template = HUD_I18N[HUD_FALLBACK_LOCALE][key] || key;
  if (!params) return template;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_match, name) =>
    params[name] !== undefined && params[name] !== null ? String(params[name]) : `{${name}}`
  );
}
